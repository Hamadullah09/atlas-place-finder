/** The pages for a country code, falling back to its English name. */
export function findCountryReference(
  countryCode: string | undefined,
  country?: string,
): CountryReference | undefined {
  const byCode = countryCode ? COUNTRY_REFERENCES[countryCode.trim().toUpperCase()] : undefined;
  if (byCode) return byCode;
  const wanted = country?.trim().toLowerCase();
  if (!wanted) return undefined;
  const all = Object.values(COUNTRY_REFERENCES);
  const exact = all.find((entry) => entry.country.toLowerCase() === wanted);
  if (exact || wanted.length < 4) return exact;
  // "Britain" for "United Kingdom": a name contained in the sheet's one.
  return all.find((entry) => {
    const name = entry.country.toLowerCase();
    return name.includes(wanted) || wanted.includes(name);
  });
}
